// Fetches the current arkenfox user.js and generates ArkenfoxPrefs.mjs —
// the pref set Aurelia's "Hardened" privacy level applies verbatim.
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src", "aurelia", "setup", "ArkenfoxPrefs.mjs");

const res = await fetch("https://raw.githubusercontent.com/arkenfox/user.js/master/user.js");
if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
const text = await res.text();

const version = text.match(/\* version:\s*(\S+)/)?.[1] ?? "unknown";
const prefs = [];
for (const raw of text.split("\n")) {
  const line = raw.trim();
  // only active declarations; commented-out (// or inside /* */ sections that
  // arkenfox always writes as line comments) are skipped by this prefix test
  if (!line.startsWith("user_pref(")) continue;
  const m = line.match(/^user_pref\("([^"]+)",\s*(.+?)\);/);
  if (!m) continue;
  const name = m[1];
  let v = m[2].trim();
  let value;
  if (v === "true" || v === "false") value = v === "true";
  else if (/^-?\d+$/.test(v)) value = parseInt(v, 10);
  else if (v.startsWith('"')) value = JSON.parse(v.replace(/\\'/g, "'"));
  else continue; // expressions we don't understand — skip
  prefs.push([name, value]);
}

const body = `/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */

/* GENERATED by scripts/make-arkenfox.mjs — do not edit by hand.
 * Source: arkenfox user.js version ${version}
 * Applied verbatim by the Setup panel's "Hardened" privacy level. */

export const ARKENFOX_VERSION = ${JSON.stringify(version)};

export const ARKENFOX_PREFS = ${JSON.stringify(prefs, null, 2)};
`;
writeFileSync(out, body);
console.log(`arkenfox ${version}: ${prefs.length} prefs -> ${out}`);
